import { readdir, readFile, writeFile, mkdir, unlink, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
const root = path.join(publicDir, 'assets');
const output = path.join(root, 'generated');
const manifestPath = fileURLToPath(new URL('../src/data/imageVariants.generated.js', import.meta.url));
const manifest = {};
const expected = new Set();
await mkdir(output, { recursive: true });
async function walk(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (filename === output) continue;
    if (entry.isDirectory()) { await walk(filename); continue; }
    if (!/\.(png|jpe?g|webp)$/i.test(filename)) continue;
    const input = await readFile(filename);
    const metadata = await sharp(input).metadata();
    if (metadata.pages > 1) continue;
    const src = '/' + path.relative(publicDir, filename).split(path.sep).join('/');
    const logo = /\/organizations\/|\/icons\/|[-/]icon\./.test(src);
    const portrait = src.includes('/portraits/');
    const widths = logo ? [48, 96] : portrait ? [192, 400] : [96, 192, 480, 960, 1600];
    const digest = createHash('sha256').update(input).update('webp-q88-v1').digest('hex').slice(0, 12);
    const variants = [];
    const sizes = [...new Set(widths.map((width) => Math.min(width, metadata.width)))];
    for (const width of sizes) {
      const name = `${path.basename(filename, path.extname(filename))}-${digest}-${width}.webp`;
      const destination = path.join(output, name);
      try { await stat(destination); } catch {
        await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 88, effort: 5 }).toFile(destination);
      }
      // Keep the original if a converted version is larger at full resolution.
      if (width === metadata.width && (await stat(destination)).size >= input.length) {
        variants.push({ src, width });
        continue;
      }
      expected.add(name);
      variants.push({ src: '/assets/generated/' + name, width });
    }
    manifest[src] = { width: metadata.width, height: metadata.height, variants };
  }
}
await walk(root);
for (const name of await readdir(output)) if (!expected.has(name)) await unlink(path.join(output, name));
const source = '// Generated by npm run prepare:images. Edit original assets, not this file.\nexport const imageVariants = ' + JSON.stringify(manifest, null, 2) + ';\n';
let old = '';
try { old = await readFile(manifestPath, 'utf8'); } catch {}
if (old !== source) await writeFile(manifestPath, source);
console.log(`Prepared responsive variants for ${Object.keys(manifest).length} images (cached by content hash).`);
